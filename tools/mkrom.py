# Generate src/rom101_data.h from the SH-101 mask ROM dump.
#
# Runs as a PlatformIO pre-script and standalone (the sim Makefile calls it).
# The dump (SH101-reference/80C49_SH101.bin) is Roland's copyrighted mask ROM
# and follows the SuperOS-303 policy: NEVER distributed, never tracked. When
# the dump is absent a stub header is emitted (ROM101_PRESENT 0) and the
# firmware refuses to boot emulator mode, falling back to SuperOS.
import os

try:
    Import("env")  # noqa: F821 -- defined when run inside PlatformIO/SCons
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except Exception:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BIN = os.path.join(ROOT, "SH101-reference", "80C49_SH101.bin")
OUT = os.path.join(ROOT, "src", "rom101_data.h")

HEAD = (
    "// GENERATED by tools/mkrom.py -- DO NOT EDIT, DO NOT DISTRIBUTE.\n"
    "// Contains the Roland SH-101 mask ROM when ROM101_PRESENT is 1.\n"
    "#pragma once\n#include <stdint.h>\n"
)

def build():
    if os.path.exists(BIN):
        data = open(BIN, "rb").read()
        if len(data) != 2048:
            raise SystemExit("mkrom: %s is %d bytes, expected 2048" % (BIN, len(data)))
        rows = []
        for i in range(0, 2048, 16):
            rows.append(",".join("0x%02X" % b for b in data[i:i + 16]))
        return (HEAD + "#define ROM101_PRESENT 1\n"
                "static const uint8_t ROM101[2048] PROGMEM = {\n"
                + ",\n".join(rows) + "\n};\n")
    return (HEAD + "#define ROM101_PRESENT 0\n"
            "static const uint8_t ROM101[2048] PROGMEM = {0};\n")

body = build()
old = open(OUT).read() if os.path.exists(OUT) else None
if body != old:
    open(OUT, "w").write(body)
    print("mkrom: wrote %s (ROM %s)" % (OUT, "embedded" if "PRESENT 1" in body else "ABSENT - stub"))
